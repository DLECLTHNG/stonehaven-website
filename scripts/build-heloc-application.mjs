// Keep the sensitive page to one integrity-pinned script, with no runtime imports.
import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
const validation=readFileSync('js/heloc-application-validation.mjs','utf8');
const entry=readFileSync('js/heloc-application.mjs','utf8');
const importLine="import {states, validateApplicant, maskSsn, validateSubjectProperty} from './heloc-application-validation.mjs';";
if(!entry.startsWith(importLine))throw new Error('Unexpected application imports; review the private-page bundle builder.');
const bundle='// Generated by scripts/build-heloc-application.mjs. Edit the source modules.\n'+validation+'\n'+entry.slice(importLine.length).trimStart();
if(/\bimport\s*(?:\(|[{*])/.test(bundle))throw new Error('Application bundle must not import other scripts.');
const integrity='sha384-'+createHash('sha384').update(bundle).digest('base64');
writeFileSync('js/heloc-application.bundle.mjs',bundle);
for(const file of ['heloc-application.html','_headers']){
 const source=readFileSync(file,'utf8');
 writeFileSync(file,source.replace(/sha384-[A-Za-z0-9+/=]+/g,integrity));
}
