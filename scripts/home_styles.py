"""Reduce the homepage's measured blocking CSS requests, preserving cascade order."""
import hashlib
import re
from pathlib import Path


def bundle(text, path, root):
    if path not in ['/', '/es/']:
        return text
    chunks = []
    names = []
    def collect(match):
        tag = match[0]
        if not re.search(r'rel="stylesheet"', tag):
            return tag
        href = re.search(r'href="([^"]+)"', tag)
        if not href or '://' in href[1]:
            return tag
        name = Path(href[1].split('?')[0]).name
        if name not in {'styles.css', 'funnel.css', 'seo-resources.css', 'home-funded.css', 'inquiry-journeys.css', 'search-navigation.css'}:
            return tag
        names.append(name)
        chunks.append('/* '+name+' */\n'+(root/name).read_text())
        return '<!-- HOME-STYLES -->' if len(chunks) == 1 else ''
    head, body = text.split('</head>', 1)
    head = re.sub(r'<link\b[^>]*>', collect, head)
    if len(chunks) != 6:
        raise ValueError('Homepage CSS inventory changed: '+repr(names))
    css = '/* Generated by scripts/home_styles.py. Edit the source stylesheets. */\n'+'\n'.join(chunks).rstrip()+'\n'
    (root/'home-page.css').write_text(css)
    version = hashlib.sha256(css.encode()).hexdigest()[:12]
    head = head.replace('<!-- HOME-STYLES -->', '<link rel="stylesheet" href="/home-page.css?v='+version+'"/>')
    return head+'</head>'+body
