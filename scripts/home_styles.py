"""Reduce the homepage's measured blocking CSS requests, preserving cascade order."""
import hashlib
import re
from pathlib import Path


def bundle(text, path, root):
    if path not in ['/', '/es/']:
        return text
    chunks = []
    names = []
    def collect(match):
        tag = match[0]
        if not re.search(r'rel="stylesheet"', tag):
            return tag
        href = re.search(r'href="([^"]+)"', tag)
        if not href or '://' in href[1]:
            return tag
        name = Path(href[1].split('?')[0]).name
        if name not in {'styles.css', 'funnel.css', 'seo-resources.css', 'home-funded.css', 'inquiry-journeys.css', 'search-navigation.css'}:
            return tag
        names.append(name)
        chunks.append('/* '+name+' */\n'+(root/name).read_text())
        return '<!-- HOME-STYLES -->' if len(chunks) == 1 else ''
    head, body = text.split('</head>', 1)
    head = re.sub(r'<link\b[^>]*>', collect, head)
    if len(chunks) != 6:
        raise ValueError('Homepage CSS inventory changed: '+repr(names))
    chunks.insert(0, (root/'home-fonts.css').read_text())
    head = re.sub(r'<link\b[^>]*href="https://fonts\.(?:googleapis|gstatic)\.com[^"]*"[^>]*>', '', head)
    preloads = ''.join('<link rel="preload" as="font" type="font/woff2" crossorigin href="/assets/fonts/'+name+'-normal-latin-20261018.woff2"/>' for name in ['inter', 'cormorant'])
    preloads += '<link rel="preload" as="font" type="font/woff2" crossorigin href="/assets/fonts/cormorant-italic-latin-20261018.woff2"/>'
    head = head.replace('<!-- HOME-STYLES -->', preloads+'<!-- HOME-STYLES -->')
    css = '/* Generated by scripts/home_styles.py. Edit the source stylesheets. */\n'+'\n'.join(chunks).rstrip()+'\n'
    (root/'home-page.css').write_text(css)
    version = hashlib.sha256(css.encode()).hexdigest()[:12]
    # Homepage CSS is small compressed, so ship it with the document to remove
    # the render-blocking round trip. Preserve selector whitespace and calc().
    compact = re.sub(r'/\*.*?\*/', '', css, flags=re.S)
    compact = re.sub(r'\s+', ' ', compact)
    compact = re.sub(r'\s*([{};])\s*', r'\1', compact).strip()
    head = head.replace('<!-- HOME-STYLES -->', '<style id="home-styles" data-version="'+version+'">'+compact+'</style>')
    body = body.replace('site-config.js?v=6', 'site-config.js?v=7').replace('funnel.js?v=15', 'funnel.js?v=16')
    body = body.replace('<script src="js/site-config', '<script src="/js/home-vendors.js?v=1" defer></script>\n<script src="js/site-config')
    body = body.replace('<script src="../js/site-config', '<script src="/js/home-vendors.js?v=1" defer></script>\n<script src="../js/site-config')
    return head+'</head>'+body
